// Writes syntaxes/stos.tmLanguage.json (the highlighting grammar) from data/stos-commands.json.
// Usage: npm run grammar   (run it again whenever the command database changes; a test checks it is up to date)
//
// A TextMate grammar is a list of regular expressions, each giving matching text a "scope" name such as
// keyword.control.stos. The colour theme decides the colour of each scope. The rules for strings,
// numbers, comments, labels and #directives are written by hand below; the command names come from the
// database, so highlighting, completion and hover always know the same commands.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DB = path.join(ROOT, 'data/stos-commands.json');
const OUT = path.join(ROOT, 'syntaxes/stos.tmLanguage.json');

/** Regex-escape a piece of text. */
const esc = s => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');

/** Before and after a command name: no letter, digit, _, $, # or @ (so "print" is not found in "printer"). */
const BEFORE = '(?<![A-Za-z0-9_$#@])';
const AFTER = '(?![A-Za-z0-9_$#])';

/**
 * The scope for a database entry. Word operators, constants and control flow get their own scopes,
 * so most themes colour them differently from ordinary instructions.
 */
function scopeOf(c) {
    if (c.kind === 'operator') { return /^[a-z]/.test(c.name) ? 'keyword.operator.word.stos' : 'keyword.operator.stos'; }
    if (['true', 'false', 'pi'].includes(c.name)) { return 'constant.language.stos'; }
    if (c.kind === 'function') { return 'support.function.stos'; }
    if (c.kind === 'property') { return 'variable.language.stos'; }
    if (c.category === 'Control' || c.category === 'Errors') { return 'keyword.control.stos'; }
    return 'keyword.other.stos';
}

/**
 * The regex for one word name. Spaces inside the name match any number of spaces ("move   x").
 * If a longer name starts with this one ("default" and "default physic"), a look-ahead keeps the short
 * name from matching the start of the long one, whatever pattern comes first in the grammar.
 */
function namePattern(name, allNames) {
    const longer = allNames
        .filter(n => n.startsWith(name + ' '))
        .map(n => n.slice(name.length + 1).split(' ').map(esc).join('\\s+') + AFTER);
    const words = name.split(' ').map(esc).join('\\s+');
    return words + (longer.length ? `(?!\\s+(?:${longer.join('|')}))` : '') + AFTER;
}

/** Build the grammar object from the list of commands. */
function buildGrammar(commands) {
    const wordNames = [...new Set(commands.map(c => c.name).filter(n => /^[a-z]/.test(n)))];
    // group the names by scope; longest names first inside each group
    const groups = new Map();
    for (const c of commands) {
        if (!/^[a-z]/.test(c.name) || c.name === 'rem') { continue; }   // rem is a comment rule
        const scope = scopeOf(c);
        if (!groups.has(scope)) { groups.set(scope, new Set()); }
        groups.get(scope).add(c.name);
    }
    const commandRules = [...groups.entries()]
        .sort(([a], [b]) => a.localeCompare(b))          // stable output, so the file only changes when the data does
        .map(([scope, names]) => ({
            name: scope,
            match: `(?i)${BEFORE}(?:${[...names].sort((a, b) => b.length - a.length || a.localeCompare(b))
                .map(n => namePattern(n, wordNames)).join('|')})`,
        }));
    // operators written as symbols, longest first so "<=" is not read as "<" and "="
    const symbols = commands.filter(c => !/^[a-z]/.test(c.name)).map(c => c.name)
        .sort((a, b) => b.length - a.length || a.localeCompare(b));

    return {
        $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
        name: 'STOS BASIC',
        scopeName: 'source.stos',
        comment: 'Generated by scripts/build-grammar.js from data/stos-commands.json. Do not edit by hand.',
        patterns: [
            { include: '#directive' },
            { include: '#line-number' },
            { include: '#source-comment' },
            { include: '#label-definition' },
            { include: '#comment' },
            { include: '#string' },
            { include: '#label' },
            { include: '#number' },
            { include: '#commands' },
            { include: '#operator' },
            { include: '#separator' },
        ],
        repository: {
            directive: {
                comment: '#include "file" and #lineinc n, at the start of a line (read by the STOS Studio converter)',
                match: '(?i)^\\s*(#(?:include|lineinc))\\b(.*)$',
                captures: {
                    1: { name: 'keyword.control.directive.stos' },
                    2: { patterns: [{ include: '#string' }, { include: '#number' }] },
                },
            },
            'line-number': {
                comment: 'a line number at the start of a line, as in an .asc file',
                match: '^\\s*(\\d+)',
                captures: { 1: { name: 'constant.numeric.line-number.stos' } },
            },
            'source-comment': {
                comment: "a line starting with ' or // (after any labels) is a comment the converter drops",
                match: "^\\s*((?:@[\\p{L}\\p{N}_]+\\s*)*)((?:'|//).*)$",
                captures: {
                    1: { name: 'entity.name.function.label.stos' },
                    2: { name: 'comment.line.source.stos' },
                },
            },
            'label-definition': {
                comment: 'a @label at the start of a line marks that line',
                match: '^\\s*(@[\\p{L}\\p{N}_]+)',
                captures: { 1: { name: 'entity.name.function.label.stos' } },
            },
            label: {
                comment: 'a @label used instead of a line number (goto @loop)',
                match: '@[\\p{L}\\p{N}_]+',
                name: 'entity.name.label.stos',
            },
            comment: {
                comment: 'REM: the rest of the line is a comment',
                match: `(?i)${BEFORE}(rem)${AFTER}(.*)$`,
                captures: {
                    1: { name: 'comment.line.rem.stos keyword.other.rem.stos' },
                    2: { name: 'comment.line.rem.stos' },
                },
            },
            string: {
                comment: 'STOS strings have no escape characters; a string may run to the end of the line',
                match: '"[^"]*(?:"|$)',
                name: 'string.quoted.double.stos',
            },
            number: {
                patterns: [
                    { name: 'constant.numeric.hex.stos', match: `${BEFORE}\\$[0-9A-Fa-f]+` },
                    { name: 'constant.numeric.binary.stos', match: `${BEFORE}%[01]+` },
                    {
                        name: 'constant.numeric.decimal.stos',
                        match: '(?i)(?<![A-Za-z0-9_$#@.])(?:\\d+\\.?\\d*|\\.\\d+)(?:e[+-]?\\d+)?(?![A-Za-z_$#])',
                    },
                ],
            },
            commands: { patterns: commandRules },
            operator: {
                name: 'keyword.operator.stos',
                match: symbols.map(esc).join('|'),
            },
            separator: {
                comment: 'the colon between two instructions on one line',
                match: ':',
                name: 'punctuation.separator.statement.stos',
            },
        },
    };
}

/** The grammar as the text of the .json file. */
function grammarText(commands) {
    return JSON.stringify(buildGrammar(commands), null, '\t') + '\n';
}

module.exports = { buildGrammar, grammarText, OUT, DB };

if (require.main === module) {
    const commands = JSON.parse(fs.readFileSync(DB, 'utf8')).commands;
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, grammarText(commands));
    console.log(`wrote ${path.relative(ROOT, OUT)} (${commands.length} commands)`);
}
